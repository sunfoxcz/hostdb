package sshconfig

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"hostdb/internal/store"
)

const Header = "# Generated by hostdb. Do not edit manually.\n"

func Generate(hosts []store.Host) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(Header)
	for _, h := range hosts {
		if !h.Enabled {
			continue
		}
		if err := store.ValidateHost(h); err != nil {
			return nil, fmt.Errorf("host %q: %w", h.Name, err)
		}
		fmt.Fprintf(&b, "\nHost %s", h.Name)
		for _, alias := range h.Aliases {
			if err := store.HostName(alias); err != nil {
				return nil, err
			}
			fmt.Fprintf(&b, " %s", alias)
		}
		fmt.Fprintf(&b, "\n    HostName %s\n", strings.ReplaceAll(h.Hostname, "%", "%%"))
		if h.User != "" {
			fmt.Fprintf(&b, "    User %s\n", h.User)
		}
		fmt.Fprintf(&b, "    Port %d\n", h.Port)
		for _, o := range h.Options {
			if err := errors.Join(store.OptionName(o.Name), store.OptionValue(o.Name, o.Value)); err != nil {
				return nil, fmt.Errorf("host %q, directive %q: %w", h.Name, o.Name, err)
			}
			fmt.Fprintf(&b, "    %s %s\n", o.Name, o.Value)
		}
	}
	return b.Bytes(), nil
}

func DefaultPath() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(home, ".ssh", "config.d", "hostdb.generated"), nil
}

func Sync(ctx context.Context, path string, hosts []store.Host) error {
	data, err := Generate(hosts)
	if err != nil {
		return err
	}
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0700); err != nil {
		return err
	}
	info, err := os.Lstat(path)
	replace := err == nil
	switch {
	case err == nil:
		if !info.Mode().IsRegular() {
			return fmt.Errorf("refusing to replace non-regular SSH file %q", path)
		}
		f, err := os.Open(path)
		if err != nil {
			return err
		}
		header := make([]byte, len(Header))
		_, readErr := io.ReadFull(f, header)
		f.Close()
		if readErr != nil || string(header) != Header {
			return fmt.Errorf("refusing to overwrite SSH file %q without the hostdb header", path)
		}
	case !errors.Is(err, os.ErrNotExist):
		return err
	}
	tmp, err := os.CreateTemp(dir, ".hostdb-ssh-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if ssh, err := exec.LookPath("ssh"); err == nil {
		if _, err := effective(ctx, ssh, tmp.Name(), "hostdb-config-check.invalid"); err != nil {
			return fmt.Errorf("OpenSSH rejected the generated configuration: %w", err)
		}
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	if replace {
		current, err := os.Lstat(path)
		if err != nil {
			return err
		}
		if !os.SameFile(info, current) {
			return fmt.Errorf("SSH file %q changed while generating its replacement", path)
		}
		if err := os.Rename(tmp.Name(), path); err != nil {
			return err
		}
	} else if err := os.Link(tmp.Name(), path); err != nil {
		return err
	}
	parent, err := os.Open(dir)
	if err != nil {
		return err
	}
	defer parent.Close()
	return parent.Sync()
}

// Directive splits an ssh_config line and preserves the raw option arguments.
func Directive(line string) (key, value string) {
	line = strings.TrimLeft(line, " \t")
	if line == "" || strings.HasPrefix(line, "#") {
		return "", ""
	}
	i := strings.IndexAny(line, " \t=")
	if i < 0 {
		return line, ""
	}
	key = line[:i]
	value = strings.TrimLeft(line[i:], " \t")
	if strings.HasPrefix(value, "=") {
		value = strings.TrimLeft(value[1:], " \t")
	}
	return key, value
}
